export type Strings = typeof de

function offsetText(o: Offset, kind: 'chip' | 'label'): string {
  if (o.n === 0) return 'Am Tag'
  const unit =
    o.unit === 'd' ? (o.n === 1 ? 'Tag' : 'Tage') : o.unit === 'w' ? (o.n === 1 ? 'Woche' : 'Wochen') : o.n === 1 ? 'Monat' : 'Monate'
  if (kind === 'chip' && !(o.n === 1 && o.unit === 'd')) return `${o.n} ${unit}`
  return `${o.n} ${unit} vorher`
}

function offsetTextEn(o: Offset, kind: 'chip' | 'label'): string {
  if (o.n === 0) return 'On the day'
  const unit = o.unit === 'd' ? 'day' : o.unit === 'w' ? 'week' : 'month'
  const u = o.n === 1 ? unit : `${unit}s`
  if (kind === 'chip' && !(o.n === 1 && o.unit === 'd')) return `${o.n} ${u}`
  return `${o.n} ${u} before`
}

